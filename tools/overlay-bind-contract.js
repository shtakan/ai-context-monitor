// Контракт связки core/gemini-overlay.js <-> core/gemini-intercept.js (Phase 3 Step 13.1).
//
// ЧТО ЭТО. Список имён ядра, которые перенесённый в core/gemini-overlay.js кластер
// оверлея читает и/или пишет. Блок `aiCmGeminiOverlay.__bind({...})` в ядре строится
// ИМЕННО из этого массива, а tools/apply-overlay-extraction.js сверяет блок с массивом
// в обе стороны. Один источник правды: добавил имя в контракт — оно обязано появиться
// в блоке __bind, и наоборот.
//
// ПОЧЕМУ КОНТРАКТ ТАКОЙ КОРОТКИЙ. Кластер оверлея почти самодостаточен: восемь из
// девяти перенесённых объявлений (aiCmIsGeminiHost, aiCmOverlayTheme, наблюдатель темы,
// aiCmApplyOverlayTheme, aiCmWatchOverlayTheme, aiCmSetScrollOverlay,
// forceRestoreVisibility и слушатели pagehide/visibilitychange) связаны друг с другом
// ВНУТРИ модуля и вызывают друг друга по прежним именам. Наружу торчат ровно три имени.
//
// ВИДЫ СВЯЗИ:
//   fn — `function имя(...)` в ядре. Передаётся ЗНАЧЕНИЕМ (имя: имя). Объявления в ядре
//        хойстятся, поэтому к моменту __bind значение уже есть.
//   rw — живое состояние: get + set. Без set запись из модуля молча теряется
//        (присваивание в accessor без сеттера не бросает), и ядро остаётся со старым
//        значением — тихий баг: снятие оверлея перестало бы обнулять aiCmScrollOverlay,
//        и forceRestoreVisibility/rerun-overlay-disarm не увидели бы, что оверлея нет.
//   ro — только чтение: get. В этом кластере таких имён нет.
//
// ЧЕГО В КОНТРАКТЕ НЕТ И ПОЧЕМУ.
//   aiCmRerunOverlayTimer (ядро, строка 1596) — состояние ре-рана лоадера; кластер
//     оверлея его не читает и не пишет (это делает пагинация). Остаётся в ядре, в
//     контракт не входит: лишний геттер расширил бы поверхность связи без нужды.
//   aiCmOverlayThemeWatcher — НЕ состояние ядра: объявлен внутри перенесённого
//     диапазона, уехал в модуль вместе с наблюдателем. Ссылка на него — локальная.
//   debugLog — свободный глобал MAIN-мира (utils/debug.js), а не имя ядра.
